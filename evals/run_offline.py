"""Offline evaluator self-test, not a model-quality benchmark."""
import argparse
import hashlib
import json
import pathlib
import re
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent
HEADINGS = {
    "en": ["Tutorial", "How-to Guide", "Reference", "Explanation"],
    "fr": ["Tutoriel", "Guide pratique", "Référence", "Explication"],
}
FRAME = re.compile(r"frame_\d+\.png", re.IGNORECASE)


def normalize(value):
    return " ".join(unicodedata.normalize("NFC", value).casefold().split())


def inspect_output(case, output):
    if not isinstance(output, str) or len(output.encode("utf-8")) > 65536:
        raise ValueError("Expected bounded Markdown text")
    normalized = normalize(output)
    headings = re.findall(r"^## ([^\r\n]+)$", output, flags=re.MULTILINE)
    frames = {name.lower() for name in FRAME.findall(output)}
    return {
        "sections": headings == HEADINGS[case["language"]],
        "required_literals": all(normalize(f) in normalized for f in case["required_facts"]),
        "unsupported_literals_absent": all(normalize(f) not in normalized for f in case["unsupported_claims"]),
        "frame_allowlist": frames <= set(case["allowed_frames"]),
    }


def reference_output(case):
    # Deliberately constructed from the same fixture, not generated by a model.
    title = "# Synthetic evaluator reference"
    sections = HEADINGS[case["language"]]
    facts = "\n".join("- " + f for f in case["required_facts"])
    frame = case["allowed_frames"][0]
    return f"{title}\n\n## {sections[0]}\n{facts}\n![fixture]({frame})\n\n" + "\n\n".join(
        f"## {heading}\n{case['required_facts'][0]}" for heading in sections[1:]
    ) + "\n"


def variants(case):
    good = reference_output(case)
    return {
        "reference": (good, None),
        "missing_section": (good.replace("## " + HEADINGS[case["language"]][-1], "### Removed"), "sections"),
        "missing_fact": (good.replace(case["required_facts"][-1], "REMOVED"), "required_literals"),
        "unsupported_literal": (good + "\n" + case["unsupported_claims"][0], "unsupported_literals_absent"),
        "invented_frame": (good + "\n![invented](frame_999999.png)", "frame_allowlist"),
    }


def run():
    raw = (ROOT / "cases-v1.json").read_bytes()
    fixture = json.loads(raw)
    if fixture["schema_version"] != "1.0":
        raise ValueError("Unexpected fixture version")
    cases = fixture["cases"]
    if len(cases) != 4 or len({c["id"] for c in cases}) != 4:
        raise ValueError("Unexpected fixture inventory")
    observations = []
    for case in cases:
        for variant, (output, expected_failure) in variants(case).items():
            expected = {key: key != expected_failure for key in (
                "sections", "required_literals", "unsupported_literals_absent", "frame_allowlist"
            )}
            actual = inspect_output(case, output)
            observations.append({
                "case": case["id"], "variant": variant, "expected": expected,
                "actual": actual, "passed": actual == expected,
                "output_sha256": hashlib.sha256(output.encode()).hexdigest(),
            })
    return {
        "schema_version": "1.0", "mode": "offline_evaluator_self_test",
        "fixture_sha256": hashlib.sha256(raw).hexdigest(),
        "cases": len(cases), "executions": len(observations),
        "passed": sum(o["passed"] for o in observations),
        "live_model_quality": None, "human_review": None,
        "observations": observations,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=pathlib.Path)
    args = parser.parse_args()
    report = run()
    rendered = json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(rendered, encoding="utf-8")
    else:
        print(rendered, end="")
    return 0 if report["passed"] == report["executions"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
